/* ================= LANGUAGE SYSTEM ================= */
// Get saved language or default to English
let currentLang = localStorage.getItem("prajaSevaLanguage") || "en";

function initLanguageSystem() {
    // Set select element if it exists
    const langSelect = document.getElementById("langSelector");
    if(langSelect) {
        langSelect.value = currentLang;
    }
    
    applyTranslations();

    // Re-render currently open dynamic content (Cards, Schemes) if they are visible
    if (typeof reRenderModal === "function") {
        reRenderModal();
    }
}

function changeLanguage(lang) {
    currentLang = lang;
    localStorage.setItem("prajaSevaLanguage", lang);
    applyTranslations();

    // Re-render currently open dynamic content
    if (typeof reRenderModal === "function") {
        reRenderModal();
    }
}

function applyTranslations() {
    const dict = translations[currentLang];
    
    // Translate text elements
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (dict[key]) {
            el.innerHTML = dict[key];
        }
    });

    // Translate placeholders
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (dict[key]) {
            el.setAttribute("placeholder", dict[key]);
        }
    });
}

function t(key) {
    return translations[currentLang][key] || key;
}

// Run on load
document.addEventListener("DOMContentLoaded", initLanguageSystem);
